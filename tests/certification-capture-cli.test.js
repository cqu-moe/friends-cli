import assert from 'node:assert/strict';
import {test} from 'node:test';
import {execFile} from 'node:child_process';
import {promisify} from 'node:util';
import {mkdir,readFile,writeFile} from 'node:fs/promises';
import {join,resolve} from 'node:path';
import {setupCertification} from './fixtures/certification-setup.mjs';
const exec=promisify(execFile),cli=resolve('dist/cli/main.js');
const run=(args,env)=>exec(process.execPath,[cli,...args],{env,timeout:25000});
test('CLI captures an explicitly returned page, rejects stale revisions, and resumes only selected draft changes',async t=>{
 const f=await setupCertification(t);const config=JSON.parse(await readFile(f.config,'utf8'));config.executeSession=true;config.state=join(f.home,'state.json');await writeFile(f.config,JSON.stringify(config));
 await mkdir(f.env.FRIENDS_DRAFT_HOME,{mode:0o700});const path=join(f.env.FRIENDS_DRAFT_HOME,'draft-1.json');await writeFile(path,JSON.stringify(f.options.draft),{mode:0o600});
 const ego=['--via','ego','--ego-task-space','7','--ego-page','p2'];
 await run(['drafts','prepare','draft-1',...ego],f.env);
 const human=JSON.parse(await readFile(config.state,'utf8'));human.rows[0].hours=8;human.rows[1].selected=false;await writeFile(config.state,JSON.stringify(human));
 const args=['drafts','capture','draft-1',...ego,'--expected-revision','1'];
 await assert.rejects(()=>run(args,f.env),e=>e.code===2&&JSON.parse(e.stdout).error.code==='INVALID_INPUT');
 assert.equal(JSON.parse(await readFile(config.state,'utf8')).ownership,'user');
 const {stdout,stderr}=await run([...args,'--user-returned-control'],f.env);const receipt=JSON.parse(stdout);
 assert.equal(stderr,'');assert.equal(receipt.schemaVersion,1);assert.equal(receipt.data.draft.durations['20210001'],8);assert.deepEqual(receipt.data.draft.includedStudentNos,['20210001']);assert.equal(receipt.data.draft.revision,2);assert.equal(receipt.data.submitted,false);assert.equal(stdout.includes('ego-fixture-token'),false);
 const after=await readFile(path,'utf8');
 await assert.rejects(()=>run([...args,'--user-returned-control'],f.env),e=>{const result=JSON.parse(e.stdout);assert.equal(e.code,5);assert.match(result.error.message,/revision conflict/);return true;});
 assert.equal(await readFile(path,'utf8'),after);
 const patch=join(f.home,'patch.json');await writeFile(patch,JSON.stringify({durations:{'20210001':8,'20210002':3}}));
 await run(['drafts','edit','draft-1','--expected-revision','2','--input',patch],f.env);
 const resumed=JSON.parse((await run(['drafts','prepare','draft-1',...ego],f.env)).stdout);assert.equal(resumed.data.submitted,false);assert.deepEqual(resumed.data.page.selectedStudentNos,['20210001']);
 assert.equal(f.requests.some(r=>r.url.endsWith('/school-activity-attestation-apply/apply')),false);
 const help=await run(['drafts','capture','--help'],f.env);assert.match(help.stdout,/user-returned-control/);
 const schema=JSON.parse((await run(['schema','drafts.capture'],f.env)).stdout);assert.equal(schema.data.localWrite,true);assert.equal(schema.data.finalSubmission,'human-only');
});
